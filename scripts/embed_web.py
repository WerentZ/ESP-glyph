#!/usr/bin/env python3
"""Embeds web/index.html into src/web_assets.h.

The animation editor is no longer embedded in the firmware: it lives
as a separate editor.html file and is opened locally on the phone.

The script runs before every PlatformIO build (extra_scripts).
The output file is rewritten only when its content changes, so the
build is not triggered again needlessly.
"""

from pathlib import Path

try:  # when started from PlatformIO/SCons the env variable is already exported
    Import("env")  # type: ignore[name-defined]  # noqa: F821
except Exception:
    env = None

if "__file__" in globals():
    PROJECT_DIR = Path(__file__).resolve().parent.parent
elif env is not None:
    PROJECT_DIR = Path(env.subst("$PROJECT_DIR"))
else:
    PROJECT_DIR = Path.cwd()
WEB_DIR = PROJECT_DIR / "web"
OUT_FILE = PROJECT_DIR / "src" / "web_assets.h"

PAGES = [
    ("INDEX_HTML", WEB_DIR / "index.html", "GLYPHWEB_INDEX"),
]


def build_header() -> str:
    parts = [
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "// Generated by scripts/embed_web.py from the web/ folder.",
        "// Do not edit manually: changes are overwritten on build.",
        "",
    ]

    for name, path, delim in PAGES:
        if not path.exists():
            raise FileNotFoundError(f"Web interface file not found: {path}")
        html = path.read_text(encoding="utf-8")
        if f'){delim}"' in html:
            raise ValueError(
                f"{path.name}: content contains the raw string terminator "
                f'){delim}" — choose another delimiter.'
            )
        if html.endswith("\n"):
            html = html[:-1]
        parts.append(f'static const char {name}[] PROGMEM = R"{delim}(')
        parts.append(html)
        parts.append(f'){delim}";')
        parts.append("")

    return "\n".join(parts) + "\n"


def main() -> None:
    content = build_header()
    old = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else None
    if old == content:
        print("[embed_web] web_assets.h unchanged")
        return
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(content, encoding="utf-8", newline="\n")
    print(f"[embed_web] updated {OUT_FILE.relative_to(PROJECT_DIR)}")


if __name__ == "__main__":
    main()
else:
    # Under SCons (PlatformIO pre-script) __name__ is not "__main__",
    # but the script still has to run on every build.
    main()
